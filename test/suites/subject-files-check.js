/* =============================================================================
   شاشة المادة — الوصف وتبويب «ملفّات»

   فحصٌ سلوكيّ يقود `Screens.course` الحقيقية لا نسخةً منها. ما يهمّ إثباته:

   ١. التبويب الرابع **يظهر بوجود ملفٍّ ويغيب بغيابه**. تبويبٌ يُفتح على فراغ
      يبدو عطلًا، وقائمةٌ لا يصلها الطالب تعني نوطةً رُفعت ولم يرها أحد.
   ٢. رابطٌ محفوظ بـ?tab=files لمادةٍ بلا ملفّات لا يعرض شاشةً بلا زرٍّ يقابلها.
   ٣. الوصف يُرسم مقصوصًا، **ويغيب كليًّا** بلا وصف — لا فجوة محجوزة.
   ٤. صورة الأستاذ المصغّرة ذهبت والاسم بقي.
   ============================================================================= */
require('./render-check-lib.js');

let bad = 0;
const ok = (n, c, x = '') => { console.log((c ? 'ok   ' : 'FAIL ') + n + (x ? ' → ' + x : '')); if (!c) bad++; };

const subj = SEED.subjects.find((s) => s.id === 'fr');
const before = { desc: subj.desc, docs: subj.docs };

/** يرسم الشاشة ويعيد HTML — الشاشة الحقيقية بمعامِلاتها الحقيقية. */
const draw = (params = {}) => Screens.course({ subject: 'fr', ...params }).outerHTML;

// نصٌّ طويل عمدًا: القصّ عند سطرين لا معنى لفحصه على كلمتين
const LONG = 'مادة اللغة الفرنسية للبكالوريا كاملةً مع الأستاذ نوار بشناق — '
  + 'ستّ وحدات تغطّي المنهاج الرسمي، مع تمارين مصنّفة وامتحانات نموذجية '
  + 'وملفّات شرحٍ مصمَّمة للطباعة.';

// =============================================================================
// ١) بلا ملفّات ولا وصف — الحالة الافتراضية اليوم
// =============================================================================
{
  subj.desc = ''; subj.docs = [];
  const html = draw();

  ok('بلا ملفّات لا يظهر تبويب رابع', !/>ملفّات</.test(html));
  ok('والتبويبات ثلاثة', (html.match(/aria-selected=/g) || []).length === 3,
     String((html.match(/aria-selected=/g) || []).length));
  ok('وبلا وصف لا يُحجز له فراغ', !/chero__desc/.test(html));

  // الرابط القديم لا يفتح شاشةً بلا زرّ يقابلها
  const forced = draw({ tab: 'files' });
  ok('و?tab=files يسقط إلى الدروس', /class="path"/.test(forced) && !/class="files"/.test(forced));
}

// =============================================================================
// ٢) بملفّات ووصف
// =============================================================================
{
  subj.desc = LONG;
  subj.docs = [
    { id: 'doc-note', title: 'نوطة المادة كاملة', pages: 181, size: 6_300_000 },
    { id: 'doc-annex', title: 'ملحق القواعد', pages: 12, size: 400_000 },
  ];
  const html = draw();

  ok('يظهر التبويب الرابع', /aria-selected="false">ملفّات</.test(html));
  ok('والتبويبات أربعة', (html.match(/aria-selected=/g) || []).length === 4,
     String((html.match(/aria-selected=/g) || []).length));
  ok('والوصف يُرسم', /chero__desc/.test(html) && html.includes('ستّ وحدات'));

  const filesHtml = draw({ tab: 'files' });
  ok('وفتحه يعرض قائمة الملفّات', /class="files"/.test(filesHtml));
  ok('بأسماء الملفّات كما كتبها المحرِّر',
     filesHtml.includes('نوطة المادة كاملة') && filesHtml.includes('ملحق القواعد'));
  ok('وعدد الملفّات في العنوان', /ملفّات المادة \(٢\)/.test(filesHtml));
  // نفس مكوّن ملفّات الدرس لا نسخة ثانية — زرّ «فتح» دليله
  ok('ونفس بطاقة ملفّ الدرس', /class="file"/.test(filesHtml) && />فتح</.test(filesHtml));
  ok('والتبويب المفتوح معلَّم', /aria-selected="true">ملفّات/.test(filesHtml));
}

/* =============================================================================
   ٢٫٥) الترتيب — نصٌّ صريح من صاحب المنتج، لا اجتهاد

     اسم المادة · عدد الوحدات · «الوصف» عريضًا · نصّه نحيفًا · «الأستاذ»
     عريضًا · اسمه · ثم شريط التبويبات **أخيرًا**.

   الترتيب هنا ليس تفصيلًا جماليًّا: بُني مرّةً بالتبويبات فوق الوصف فرُدَّ.
   الفحص بمواضع النصّ في HTML لا بوجوده — الوجود وحده كان يمرّ أخضر
   والترتيب مقلوب.
   ============================================================================= */
{
  const html = draw();
  const at = (needle) => html.indexOf(needle);
  const order = ['chero__title', 'chero__pill', '>الوصف<', 'chero__desc',
                 '>الأستاذ<', 'chero__teacher', 'class="seg"'];
  const places = order.map(at);
  ok('كل عناصر الترويسة موجودة', places.every((i) => i !== -1),
     order.filter((_, i) => places[i] === -1).join(' · ') || 'كلّها');
  ok('وبالترتيب المطلوب حرفيًّا',
     places.every((v, i) => i === 0 || (v > places[i - 1])),
     order.map((n, i) => `${n}:${places[i]}`).join(' '));

  // «الوصف» و«الأستاذ» عنوانان عريضان بنفس النمط — لا نصٌّ صغيرٌ باهت
  ok('العنوانان بنفس صنف العنوان الفرعي',
     (html.match(/chero__lbl/g) || []).length === 2,
     String((html.match(/chero__lbl/g) || []).length));
}

// =============================================================================
// ٣) صورة الأستاذ مرّة واحدة — في الغلاف لا مكرّرة قبل اسمه
// =============================================================================
{
  // بصورةٍ فعلية: بلا صورة يرسم الغلاف أيقونة المادة، فلا شيء يمكن أن يتكرّر
  const t = SEED.teachers.find((x) => (x.subjects || []).includes('fr'));
  const wasPhoto = t.photo;
  t.photo = 'teachers/demo.jpg';

  const html = draw();
  ok('الغلاف يعرض الصورة كاملةً', /chero__photo/.test(html));
  ok('ولا تتكرّر مصغّرةً قبل اسم الأستاذ', !/chero__av/.test(html));
  ok('ومرّة واحدة لا مرّتين', (html.match(/teachers\/demo\.jpg/g) || []).length === 1,
     String((html.match(/teachers\/demo\.jpg/g) || []).length));
  // نصٌّ عاديّ تحت عنوانه، لا بطاقة رماديّة بترويسةٍ صغيرة داخلها
  ok('والاسم نصٌّ عاديّ تحت عنوانه',
     new RegExp('chero__teacher"?>' + t.name).test(html) && !/chero__tb/.test(html),
     html.slice(html.indexOf('chero__teacher'), html.indexOf('chero__teacher') + 60));

  t.photo = wasPhoto;
}

// =============================================================================
// ٤) بلا اتصال — رسالةٌ تشرح بدل بطاقاتٍ تدور بلا نهاية
// =============================================================================
{
  const wasOnline = Store.get().online;
  Store.set({ online: false });
  const html = draw({ tab: 'files' });
  ok('بلا إنترنت تُشرح الحاجة للاتصال',
     /doc__off/.test(html) && html.includes('ملفّات المادة تحتاج اتصالًا'));
  ok('ولا تُبنى بطاقات لن تُحمَّل', !/class="files"/.test(html));
  Store.set({ online: wasOnline });
}

Object.assign(subj, before);
console.log(bad ? `\n${bad} فحصًا فاشلًا` : '\nكل الفحوص نجحت');
process.exit(bad ? 1 : 0);
